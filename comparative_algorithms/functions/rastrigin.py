def rastrigin(X, pj, aj, bj, cj):
    if X.ndim > 1:
        pj = pj.reshape(-1, 1)

    term = np.sum(pj * X ** 2 - bj * np.cos(np.pi * X), axis=0)
    f = aj * term + 10 * X.shape[0] + cj
    
    return f


