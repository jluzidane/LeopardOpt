def rosenbrock(x, p, a, b, bias=0, scale=1):
    d = x.shape[0]
    f = sum(a*(1 - p[i]*x[i])**2 + b*(p[i+1]*x[i+1] - (p[i]*x[i])**2)**2 for i in range(d-1))
    f = (f-bias)*scale
    return f


