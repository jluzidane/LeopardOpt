def schwefel(X, pj, sj, bj):

    if X.ndim > 1:
        pj = pj.reshape(-1, 1)

    f = 418.9829 * X.shape[0] - np.sum(pj*X * np.sin(np.sqrt(abs(pj*X))), axis=0)
    
    return sj * f + bj


