def zakharov(X, yk, pj, sj, bj):
    i = np.arange(X.shape[0])
    if X.ndim > 1:
        pj = pj.reshape(-1, 1)
        i = i.reshape(-1, 1)

    term1 = np.sum(pj * X ** 2, axis=0)
    term2 = np.sum((i+1) * pj * X, axis=0) * 0.5
    f = term1 + term2 ** 2 + term2 ** 4
    f = sj * f + bj
    
    return f


