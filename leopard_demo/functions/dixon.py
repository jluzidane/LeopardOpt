def dixon(X, pj, aj, bj, cj):

    f = aj * (pj[0]*X[0] - 1) ** 2
    f += bj * sum((i+1) * (2 * (pj[i]*X[i]) ** 2 - pj[i-1]*X[i-1]) ** 2 for i in range(1, X.shape[0]))
    
    return f + cj


