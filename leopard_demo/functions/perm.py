def perm(X, pj, sj, bj, cj):
    dim = X.shape[0]
    if X.ndim > 1:
        pj = pj.reshape(-1, 1)
    
    f = 0
    for i in range(1, dim+1):
        term = sum((k + bj) * ((pj[k-1] * X[k-1]) ** 3 - 1 / (k ** i)) for k in range(1, dim+1))
        f += term ** 2
    
    return sj * f + cj


