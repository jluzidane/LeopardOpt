def styblinski(X, pj, sj, bj):

    if X.ndim > 1:
        pj = pj.reshape(-1, 1)

    f = 0.5 * np.sum((pj*X)**4 - 16*(pj*X)**2 + 5*(pj*X), axis=0)
    
    return sj * f + bj


